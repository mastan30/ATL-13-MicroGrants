'use strict';

export interface AgentVersionInfo {
  version: string;
  language: string;
  language_version: string;
}

export interface AgentSessionInfo {
  id: string;
  appName: string;
  userId: string;
  state?: Record<string, unknown>;
  events?: unknown[];
}

export interface AgentMessagePart {
  text?: string;
  thoughtSignature?: string;
}

export interface AgentSSEResponseData {
  modelVersion?: string;
  content?: {
    parts?: AgentMessagePart[];
    role?: string;
  };
  finishReason?: string;
  author?: string;
}

export function getOrGenerateUserId(): string {
  if (typeof window === 'undefined') return 'default_user';
  let stored = localStorage.getItem('anchor_agent_user_id');
  if (!stored) {
    stored = `user_${Math.random().toString(36).substring(2, 9)}`;
    localStorage.setItem('anchor_agent_user_id', stored);
  }
  return stored;
}

export async function getAgentVersion(): Promise<AgentVersionInfo> {
  const res = await fetch('/api/agent?action=version');
  if (!res.ok) {
    throw new Error('Failed to get agent version');
  }
  return res.json();
}

export async function getAgentApps(): Promise<string[]> {
  const res = await fetch('/api/agent?action=apps');
  if (!res.ok) {
    throw new Error('Failed to get agent apps list');
  }
  return res.json();
}

export async function createAgentSession(userId: string): Promise<AgentSessionInfo> {
  const res = await fetch('/api/agent', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ action: 'session', userId, appName: 'agent' }),
  });

  if (!res.ok) {
    throw new Error('Failed to create agent session');
  }
  return res.json();
}

export function parseSSEResponse(sseText: string): string {
  const lines = sseText.split('\n');
  let fullText = '';

  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('data:')) {
      const jsonStr = trimmed.substring(5).trim();
      try {
        const data: AgentSSEResponseData = JSON.parse(jsonStr);
        if (data.content?.parts) {
          for (const part of data.content.parts) {
            if (part.text) {
              fullText += part.text;
            }
          }
        }
      } catch (e) {
        console.warn('Failed to parse SSE JSON chunk:', e);
      }
    }
  }

  return fullText;
}

export async function sendAgentMessage(
  sessionId: string,
  message: string,
  userId: string
): Promise<string> {
  const res = await fetch('/api/agent', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      action: 'chat',
      appName: 'agent',
      userId,
      sessionId,
      message,
    }),
  });

  if (!res.ok) {
    throw new Error('Failed to send message to agent');
  }

  const { raw } = await res.json();
  const answer = parseSSEResponse(raw);
  return answer || 'No text response generated by agent.';
}
